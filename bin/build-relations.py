#!/usr/bin/env python3
"""Generate the Ciao relation fact module from Episteme Org files."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import importlib.util
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "relations" / "generated" / "relation_facts.pl"


def load_integrity_module():
    spec = importlib.util.spec_from_file_location(
        "episteme_check_integrity", ROOT / "bin" / "check-integrity.py"
    )
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load Episteme Org parser")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass(frozen=True, order=True)
class RelationFact:
    path: str
    line: int
    predicate: str
    target_kind: str
    target: str

    @property
    def identifier(self) -> str:
        value = f"{self.path}\0{self.line}\0{self.predicate}\0{self.target_kind}\0{self.target}"
        return "relation_" + hashlib.sha256(value.encode()).hexdigest()[:16]


def relation_facts(root: Path) -> tuple[list[RelationFact], list[object]]:
    """Return normalized relation facts and parser issues below ROOT."""
    integrity = load_integrity_module()
    documents, issues = integrity.parse_repository(root)
    facts: set[RelationFact] = set()
    for document in documents:
        path = document.relative_path.as_posix()
        facts.update(
            RelationFact(
                path,
                relation.line,
                relation.predicate.replace("-", "_"),
                "source",
                relation.target,
            )
            for relation in document.relations
        )
        facts.update(
            RelationFact(path, citation.line, "cites", "source", citation.key)
            for citation in document.citations
        )
    return sorted(facts), issues


def prolog_atom(value: str) -> str:
    """Quote VALUE as a Ciao atom."""
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r")
    return f"'{escaped}'"


def render_module(facts: list[RelationFact]) -> str:
    """Render FACTS as a deterministic Ciao module with two lookup indexes."""
    lines = [
        "% Generated by bin/build-relations.py. Do not edit.",
        ":- module(relation_facts, [",
        "    asserted/5,",
        "    from_index/5,",
        "    to_index/5",
        "], []).",
        "",
    ]
    rendered_facts = []
    for fact in facts:
        identifier = prolog_atom(fact.identifier)
        subject = f"note({prolog_atom(fact.path)})"
        predicate = fact.predicate
        target = f"{fact.target_kind}({prolog_atom(fact.target)})"
        origin = f"org({prolog_atom(fact.path)}, {fact.line})"
        rendered_facts.append((identifier, subject, predicate, target, origin))
    lines.extend(
        f"asserted({identifier}, {subject}, {predicate}, {target}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    lines.append("")
    lines.extend(
        f"from_index({subject}, {predicate}, {target}, {identifier}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    lines.append("")
    lines.extend(
        f"to_index({target}, {predicate}, {subject}, {identifier}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="Episteme repository root")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="generated Ciao module")
    parser.add_argument("--quiet", action="store_true", help="do not print the output summary")
    args = parser.parse_args(argv)

    root = args.root.expanduser().resolve()
    output = args.output.expanduser().resolve()
    if not root.is_dir():
        parser.error(f"repository root does not exist: {root}")

    facts, issues = relation_facts(root)
    errors = [issue for issue in issues if issue.severity == "ERROR"]
    if errors:
        for issue in errors:
            print(f"ERROR: {issue.path}:{issue.line}: {issue.message}", file=sys.stderr)
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix(output.suffix + ".tmp")
    temporary.write_text(render_module(facts), encoding="utf-8")
    temporary.replace(output)
    if not args.quiet:
        print(f"Wrote {output} ({len(facts)} asserted relation(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
