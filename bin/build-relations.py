#!/usr/bin/env python3
"""Generate the Ciao relation fact module from Episteme Org files."""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import hashlib
import importlib.util
import os
from pathlib import Path
from pathlib import PurePosixPath
import sys
import tempfile


ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = ROOT / "relations" / "generated" / "relation_facts.pl"


def load_integrity_module():
    spec = importlib.util.spec_from_file_location(
        "episteme_check_integrity", ROOT / "bin" / "check-integrity.py"
    )
    if spec is None or spec.loader is None:
        raise RuntimeError("cannot load Episteme Org parser")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


@dataclass(frozen=True, order=True)
class NoteRecord:
    identifier: str
    path: str
    context: str


@dataclass(frozen=True, order=True)
class RelationFact:
    note_id: str
    path: str
    line: int
    predicate: str
    target_kind: str
    target: str

    @property
    def identifier(self) -> str:
        value = f"{self.note_id}\0{self.line}\0{self.predicate}\0{self.target_kind}\0{self.target}"
        return "relation_" + hashlib.sha256(value.encode()).hexdigest()[:16]


@dataclass(frozen=True)
class CitationOccurrence:
    note_id: str
    path: str
    line: int
    column: int
    key: str
    locator: str | None

    @property
    def identifier(self) -> str:
        value = f"{self.note_id}\0{self.line}\0{self.column}\0{self.key}\0{self.locator or ''}"
        return "citation_" + hashlib.sha256(value.encode()).hexdigest()[:16]


def relation_facts(
    root: Path,
) -> tuple[
    list[NoteRecord],
    list[RelationFact],
    list[CitationOccurrence],
    list[object],
]:
    """Return normalized relation and citation facts plus parser issues."""
    integrity = load_integrity_module()
    parsed = integrity.parse_repository(root)
    documents, _ = parsed
    issues = integrity.check_repository(root, parsed=parsed)
    notes: set[NoteRecord] = set()
    facts: set[RelationFact] = set()
    citations: set[CitationOccurrence] = set()
    for document in documents:
        if not document.relations and not document.citations:
            continue
        if document.file_id is None:
            continue
        path = document.relative_path.as_posix()
        note_id = document.file_id.value
        context = document.relative_path.parent.as_posix()
        notes.add(NoteRecord(note_id, path, context))
        facts.update(
            RelationFact(
                note_id,
                path,
                relation.line,
                relation.predicate.replace("-", "_"),
                "source",
                relation.target,
            )
            for relation in document.relations
        )
        facts.update(
            RelationFact(
                note_id, path, citation.line, "cites", "source", citation.key
            )
            for citation in document.citations
        )
        citations.update(
            CitationOccurrence(
                note_id,
                path,
                citation.line,
                citation.column,
                citation.key,
                citation.locator,
            )
            for citation in document.citations
        )
    return (
        sorted(notes),
        sorted(facts),
        sorted(
            citations,
            key=lambda citation: (
                citation.path,
                citation.line,
                citation.column,
                citation.key,
                citation.locator or "",
            ),
        ),
        issues,
    )


def prolog_atom(value: str) -> str:
    """Quote VALUE as a Ciao atom."""
    escaped = value.replace("\\", "\\\\").replace("'", "\\'")
    escaped = escaped.replace("\n", "\\n").replace("\r", "\\r")
    return f"'{escaped}'"


def render_module(
    notes: list[NoteRecord],
    facts: list[RelationFact],
    citations: list[CitationOccurrence],
) -> str:
    """Render a deterministic Ciao module with bidirectional lookup indexes."""
    lines = [
        "% Generated by bin/build-relations.py. Do not edit.",
        ":- module(relation_facts, [",
        "    asserted/5,",
        "    from_index/5,",
        "    to_index/5,",
        "    asserted_citation/5,",
        "    citation_from_index/5,",
        "    citation_to_index/5,",
        "    note_index/3,",
        "    context_parent_index/2",
        "], []).",
        "",
    ]
    rendered_facts = []
    for fact in facts:
        identifier = prolog_atom(fact.identifier)
        subject = f"note({prolog_atom(fact.note_id)})"
        predicate = fact.predicate
        target = f"{fact.target_kind}({prolog_atom(fact.target)})"
        origin = f"org({prolog_atom(fact.path)}, {fact.line})"
        rendered_facts.append((identifier, subject, predicate, target, origin))
    lines.extend(
        f"asserted({identifier}, {subject}, {predicate}, {target}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    lines.append("")
    lines.extend(
        f"from_index({subject}, {predicate}, {target}, {identifier}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    lines.append("")
    lines.extend(
        f"to_index({target}, {predicate}, {subject}, {identifier}, {origin})."
        for identifier, subject, predicate, target, origin in rendered_facts
    )
    lines.append("")
    rendered_citations = []
    for citation in citations:
        identifier = prolog_atom(citation.identifier)
        note = f"note({prolog_atom(citation.note_id)})"
        source = f"source({prolog_atom(citation.key)})"
        locator = (
            "no_locator"
            if citation.locator is None
            else f"locator({prolog_atom(citation.locator)})"
        )
        origin = (
            f"org({prolog_atom(citation.path)}, {citation.line}, {citation.column})"
        )
        rendered_citations.append((identifier, note, source, locator, origin))
    lines.extend(
        f"asserted_citation({identifier}, {note}, {source}, {locator}, {origin})."
        for identifier, note, source, locator, origin in rendered_citations
    )
    lines.append("")
    lines.extend(
        f"citation_from_index({note}, {source}, {locator}, {identifier}, {origin})."
        for identifier, note, source, locator, origin in rendered_citations
    )
    lines.append("")
    lines.extend(
        f"citation_to_index({source}, {note}, {locator}, {identifier}, {origin})."
        for identifier, note, source, locator, origin in rendered_citations
    )
    lines.append("")
    lines.extend(
        f"note_index(note({prolog_atom(note.identifier)}), "
        f"{prolog_atom(note.path)}, context({prolog_atom(note.context)}))."
        for note in notes
    )
    lines.append("")
    context_edges: set[tuple[str, str]] = set()
    for note in notes:
        child = PurePosixPath(note.context)
        while child.as_posix() != ".":
            parent = child.parent
            context_edges.add((child.as_posix(), parent.as_posix()))
            child = parent
    lines.extend(
        f"context_parent_index(context({prolog_atom(child)}), "
        f"context({prolog_atom(parent)}))."
        for child, parent in sorted(context_edges)
    )
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT, help="Episteme repository root")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="generated Ciao module")
    parser.add_argument("--quiet", action="store_true", help="do not print the output summary")
    args = parser.parse_args(argv)

    root = args.root.expanduser().resolve()
    output = args.output.expanduser().resolve()
    if not root.is_dir():
        parser.error(f"repository root does not exist: {root}")

    notes, facts, citations, issues = relation_facts(root)
    errors = [issue for issue in issues if issue.severity == "ERROR"]
    if errors:
        for issue in errors:
            print(f"ERROR: {issue.path}:{issue.line}: {issue.message}", file=sys.stderr)
        return 1

    output.parent.mkdir(parents=True, exist_ok=True)
    mode = 0o644
    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{output.name}.", suffix=".tmp", dir=output.parent
    )
    temporary = Path(temporary_name)
    try:
        os.fchmod(fd, mode)
        with os.fdopen(fd, "w", encoding="utf-8") as stream:
            stream.write(render_module(notes, facts, citations))
        temporary.replace(output)
    finally:
        temporary.unlink(missing_ok=True)
    if not args.quiet:
        print(
            f"Wrote {output} ({len(notes)} note(s), {len(facts)} relation(s), "
            f"{len(citations)} citation occurrence(s))"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
